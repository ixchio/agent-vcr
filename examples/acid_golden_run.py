def simulate_step(
    recorder: VCRRecorder,
    acid: ACIDWorkspace,
    step_info: dict,
    workspace: Path,
    step_num: int,
) -> dict:
    """Simulate an agent step with realistic LLM metadata."""
    time.sleep(0.15)  # Simulate latency feel

    # Write a file to the workspace to simulate real FS side effects
    action_file = workspace / f"step_{step_num}_{step_info['node']}.py"
    action_file.write_text(
        f"# {step_info['action']}\n"
        f"# Generated by {step_info['node']} agent\n"
        f"print('Step {step_num}: {step_info['action']}')\n"
    )

    output = {
        "action": step_info["action"],
        "status": "completed",
        "files_modified": [str(action_file.name)],
    }

    # Record in VCR with full LLM metadata
    recorder.record_step(
        node_name=step_info["node"],
        input_state={"step": step_num, "task": step_info["action"]},
        output_state=output,
        metadata=FrameMetadata(
            latency_ms=step_info["latency"],
            tokens_used=step_info["tokens"],
            tokens_input=step_info["tokens"] // 3,
            tokens_output=step_info["tokens"] * 2 // 3,
            cost_usd=step_info["cost"],
        ),
    )

    # SAVEPOINT via ACID
    acid.savepoint(output, node_name=step_info["node"])

    return output


def run_full_demo():
    """The complete 60-second visceral demo."""
    workspace = Path("/tmp/acid_agent_workspace")
    vcr_dir = Path("/tmp/acid_agent_workspace/.vcr")
    golden_dir = Path("/tmp/acid_agent_workspace/.vcr/golden")

    # Clean slate
    if workspace.exists():
        shutil.rmtree(workspace)

    banner(
        "THE COMPLETE AI AGENT DEV LOOP\n"
        "PLAN → BUILD → FAIL → REWIND → FIX → SUCCEED → NEVER PAY TWICE\n"
        "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n"
        "4 Layers — Built by One Person — Nobody Else Has This",
        MAGENTA,
    )

    task = "Build a REST API for user authentication with JWT tokens"

    # ═══════════════════════════════════════════════════════════════════
    # RUN 1: THE ORIGINAL RUN (Fail → Rewind → Fix → Succeed)
    # ═══════════════════════════════════════════════════════════════════

    banner("RUN 1: ORIGINAL EXECUTION", CYAN)

    # ── Layer 1: Planning Mode ────────────────────────────────────────
    step("📋", f"Task: {BOLD}{task}{RESET}")
    print()

    recorder = VCRRecorder(output_dir=str(vcr_dir))
    acid = ACIDWorkspace(str(workspace), recorder=recorder)
    acid.begin(session_id="run_001")

    step("🧠", f"{BOLD}LAYER 1: Planning Mode{RESET} — Agent thinks before it acts", YELLOW)
    print()

    step_num = 0
    for s in PLAN_STEPS:
        step_num += 1
        simulate_step(recorder, acid, s, workspace, step_num)
        step("  ✓", f"Step {step_num}: {s['action']}", DIM)

    # Write PLAN.md
    plan_md = workspace / "PLAN.md"
    plan_md.write_text(
        "# Authentication API Plan\n\n"
        "## Architecture\n"
        "- Clean service layer pattern\n"
        "- JWT token management\n"
        "- Modular route handlers\n\n"
        "## Steps\n"
        "1. Create project structure\n"
        "2. Write base models\n"
        "3. Implement API routes\n"
        "4. Write service layer\n"
        "5. Add tests\n"
    )
    acid.savepoint({"plan": "PLAN.md written"}, node_name="planner")
    step("📄", f"PLAN.md written → {GREEN}Agent has a plan{RESET}")
    print()

    # ── Layer 2: Execution (BAD PATH) ────────────────────────────────
    step("⚡", f"{BOLD}LAYER 2: Agent Execution{RESET} — OpenHands runs the plan", YELLOW)
    print()

    rewind_point = step_num  # Save this for rollback

    for s in BUILD_STEPS_BAD:
        step_num += 1
        simulate_step(recorder, acid, s, workspace, step_num)
        if "BAD" in s["action"] or "CRASH" in s["action"]:
            step("  ✗", f"Step {step_num}: {s['action']}", RED)
        else:
            step("  ✓", f"Step {step_num}: {s['action']}", DIM)

    # Write the spaghetti file
    spaghetti = workspace / "monolith.py"
    with open(spaghetti, "w") as f:
        f.write("# MONOLITHIC HANDLER - This is the wrong architecture\n")
        f.write("class GodObject:\n")
        for i in range(200):
            f.write(f"    def do_thing_{i}(self): pass  # spaghetti line {i}\n")

    print()
    step("💀", f"{RED}{BOLD}FAILURE at step {step_num}!{RESET}", RED)
    step("📁", f"Files in workspace: {[f.name for f in workspace.iterdir() if f.is_file()]}")

    total_files = len([f for f in workspace.iterdir() if f.is_file()])
    step("📊", f"Total files created: {total_files} (including 200-line monolith.py)")
    print()

    # ── Layer 3: agent-vcr shows the failure ─────────────────────────
    step("📼", f"{BOLD}LAYER 3: agent-vcr{RESET} — Recorded {len(recorder.get_frames())} frames", YELLOW)

    frames = recorder.get_frames()
    error_frame = frames[-1]
    step("🔍", f"Failed at: {error_frame.node_name} → {error_frame.output_state.get('action', '')}")
    step("💸", f"Tokens burned so far: {sum(f.metadata.tokens_used or 0 for f in frames):,}")
    step("💰", f"Money wasted: ${sum(f.metadata.cost_usd or 0 for f in frames):.4f}")
    print()

    # ── ROLLBACK ─────────────────────────────────────────────────────
    banner("⏪ ROLLBACK TO STEP 3", RED)
    step("🔄", "Rewinding BOTH filesystem AND memory state...", YELLOW)

    acid.rollback(to_frame_index=rewind_point)
    recorder = acid.recorder  # Get the forked recorder

    files_after = [f.name for f in workspace.iterdir() if f.is_file()]
    step("📁", f"Files after rollback: {files_after}")
    assert "monolith.py" not in files_after, "Rollback failed!"
    step("✅", f"{GREEN}{BOLD}ROLLBACK SUCCESS — monolith.py is GONE from disk{RESET}")
    step("✅", f"{GREEN}World rewound. Not just the object — the actual filesystem.{RESET}")
    print()

    # ── RESUME: Good path ────────────────────────────────────────────
    banner("▶️  RESUME FROM STEP 3 — BETTER PATH", GREEN)

    for s in BUILD_STEPS_GOOD:
        step_num += 1
        simulate_step(recorder, acid, s, workspace, step_num)
        step("  ✓", f"Step {step_num}: {s['action']}", GREEN)

    print()
    step("✅", f"{GREEN}{BOLD}ALL TESTS PASS — Agent succeeded!{RESET}")

    # ── COMMIT ───────────────────────────────────────────────────────
    acid.commit()
    step("🔒", f"{GREEN}COMMIT — Successful path locked into main branch{RESET}")
    print()

    # ── Save as Golden Run ───────────────────────────────────────────
    banner("⭐ SAVING AS GOLDEN RUN", YELLOW)

    cache = GoldenRunCache(cache_dir=str(golden_dir))
    fingerprint = cache.save_golden_run(task=task, recorder=recorder, tags=["auth", "jwt"])

    step("⭐", f"Golden path saved with fingerprint: {BOLD}{fingerprint}{RESET}")
    step("💾", f"Cached at: {golden_dir / f'{fingerprint}.vcr'}")

    run1_tokens = sum(f.metadata.tokens_used or 0 for f in recorder.get_frames())
    run1_cost = sum(f.metadata.cost_usd or 0 for f in recorder.get_frames())
    run1_latency = sum(f.metadata.latency_ms or 0 for f in recorder.get_frames())

    print()
    cost_box("RUN 1: Original Execution", run1_tokens, run1_cost, run1_latency, YELLOW)

    # Show git log
    print(f"\n  {DIM}Git history:{RESET}")
    os.system(f"cd {workspace} && git log --oneline --graph --all 2>/dev/null | head -10 | sed 's/^/    /'")

    # ═══════════════════════════════════════════════════════════════════
    # RUN 2: GOLDEN REPLAY — Same task, $0.00, instant
    # ═══════════════════════════════════════════════════════════════════

    banner("RUN 2: GOLDEN REPLAY — SAME TASK", MAGENTA)
    step("🔁", f"Task: {BOLD}{task}{RESET}")
    step("⭐", "Golden run found in cache! Replaying...", GREEN)
    print()

    replay_recorder = VCRRecorder(output_dir=str(vcr_dir))
    outputs, ledger = cache.replay(
        task=task,
        recorder=replay_recorder,
    )

    for i, output in enumerate(outputs):
        action = output.get("action", output.get("plan", "replayed"))
        step("  ⚡", f"Step {i+1}: {action} {DIM}(from cache){RESET}", GREEN)

    print()
    step("✅", f"{GREEN}{BOLD}COMPLETED IN {ledger.replay_latency_ms:.0f}ms — $0.00 in LLM calls{RESET}")
    print()

    # ── THE MONEY SHOT: Cost Comparison ──────────────────────────────
    banner("💰 THE COST COMPARISON — This Number Hits Different", YELLOW)

    cost_box("RUN 1: Original", run1_tokens, run1_cost, run1_latency, RED)
    print()
    cost_box("RUN 2: Golden Replay", ledger.replay_tokens, ledger.replay_cost_usd, ledger.replay_latency_ms, GREEN)

    print()
    print(f"  {BOLD}{GREEN}┌─────────────────────────────────────────┐")
    print(f"  │  💰 SAVINGS                              │")
    print(f"  │  Tokens saved:  {ledger.tokens_saved:>10,}                │")
    print(f"  │  Cost saved:    ${ledger.cost_saved_usd:>9.4f}                │")
    print(f"  │  Time saved:    {ledger.time_saved_ms:>8.0f}ms                │")
    print(f"  │  Reduction:     {ledger.savings_percent:>7.0f}%                 │")
    print(f"  └─────────────────────────────────────────┘{RESET}")

    print()
    banner(
        "PLAN → BUILD → FAIL → REWIND → FIX → SUCCEED → NEVER PAY TWICE\n"
        "\n"
        "Nobody has closed this loop end-to-end.\n"
        "agent-vcr just did.\n"
        "\n"
        "pip install ai-agent-vcr",
        MAGENTA,
    )


if __name__ == "__main__":
    run_full_demo()
