# ── Pretty Printing ──────────────────────────────────────────────────────────

BOLD = "\033[1m"
DIM = "\033[2m"
RED = "\033[91m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
CYAN = "\033[96m"
MAGENTA = "\033[95m"
RESET = "\033[0m"
BG_RED = "\033[41m"
BG_GREEN = "\033[42m"


def banner(text: str, color: str = CYAN):
    width = 72
    print(f"\n{color}{BOLD}{'━' * width}")
    for line in text.strip().split("\n"):
        print(f"  {line}")
    print(f"{'━' * width}{RESET}\n")


def step(icon: str, msg: str, color: str = ""):
    print(f"  {color}{icon}  {msg}{RESET}")


def cost_box(label: str, tokens: int, cost: float, latency: float, color: str):
    print(f"  {color}┌─────────────────────────────────────────┐")
    print(f"  │  {label:<39}│")
    print(f"  │  Tokens:  {tokens:>10,}                    │")
    print(f"  │  Cost:    ${cost:>9.4f}                    │")
    print(f"  │  Latency: {latency:>8.0f}ms                    │")
    print(f"  └─────────────────────────────────────────┘{RESET}")


